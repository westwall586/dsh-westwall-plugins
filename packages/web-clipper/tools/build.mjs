/**
 * Bundle the browser client into client.js and wrap it in the module-loader
 * registration contract. React stays external because the loader factory
 * receives the platform require.
 */
import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const PACKAGE_ID = '@westwall/dsh-web-clipper'
const GLOBAL_NAME = 'DshWebClipperClient'
const OUT = 'client.js'
const MAX_BYTES = 1200 * 1024

const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['client/src/main.mjs'],
  bundle: true,
  format: 'iife',
  globalName: GLOBAL_NAME,
  platform: 'browser',
  target: ['es2022'],
  minify: true,
  loader: { '.css': 'text' },
  external: ['react'],
  legalComments: 'inline',
  write: false,
  charset: 'utf8',
  define: { 'process.env.NODE_ENV': '"production"' },
  logOverride: { 'empty-import-meta': 'silent' },
})

const output = `// Generated by tools/build.mjs; do not edit.
// Bundles defuddle. MIT License: https://github.com/Fivefold/defuddle
window.__ModuleLoader__.load({ id: '${PACKAGE_ID}', factory(require) {
${result.outputFiles[0].text}
    return ${GLOBAL_NAME}.default;
  }
});
`
const bytes = Buffer.byteLength(output)
if (bytes >= MAX_BYTES) {
  throw new Error(`tools/build.mjs: ${OUT} is ${bytes} bytes, over the ${MAX_BYTES}-byte guard`)
}
await writeFile(new URL(OUT, root), output)
console.log(`built ${OUT} (${(bytes / 1024).toFixed(0)}KB)`)