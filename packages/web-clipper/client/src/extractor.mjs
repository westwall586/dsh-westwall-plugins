/**
 * Turn one captured page into an attachment artifact.
 *
 * Body extraction and Markdown conversion come from defuddle/full. This module
 * only assembles the four-field metadata block, the full-page fallback, and a
 * legal filename. `clipped_at` is formatted from local time, never from
 * `toISOString()`, because the metadata records when the user clipped on this
 * machine.
 */
import Defuddle from 'defuddle/full'

/** Fixed English note stored in metadata so the Agent knows what to do with an incomplete snapshot. */
export const CLIP_NOTE = 'Web snapshot generated by DSH Web Clipper. If the content is incomplete, revisit the original page.'

const ILLEGAL = /[\\/:*?"<>|\u0000-\u001f]/g
const MAX_BASE = 64
const DOC_TYPE = /^\s*<!doctype[^>]*>/i

/** Page title to a legal file name; empty titles fall back to `untitled`. */
export function sanitizeFilename(title, ext) {
  let base = String(title ?? '').replace(ILLEGAL, ' ').replace(/\s+/g, ' ').trim()
  if (base.length > MAX_BASE) base = base.slice(0, MAX_BASE).trim()
  if (base === '') base = 'untitled'
  return `${base}.${ext}`
}

const pad = (value) => String(value).padStart(2, '0')

/** Sortable local timestamp for a file name; colons are illegal on Windows. */
export function fileStamp(date = new Date()) {
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
    + `_${pad(date.getHours())}-${pad(date.getMinutes())}-${pad(date.getSeconds())}`
}

/** A timestamped name so clips of the same page sort chronologically. */
export function clipFilename(title, ext, clippedAt = new Date()) {
  return `${fileStamp(clippedAt)}_${sanitizeFilename(title, ext)}`
}

/** Local ISO timestamp with a numeric UTC offset, e.g. 2026-11-14T12:30:00+08:00. */
export function localTimestamp(date = new Date()) {
  const offset = -date.getTimezoneOffset()
  const sign = offset >= 0 ? '+' : '-'
  const abs = Math.abs(offset)
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
    + `T${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`
    + `${sign}${pad(Math.floor(abs / 60))}:${pad(abs % 60)}`
}

/** The exact four metadata fields, in order. */
export function buildMetadata({ title, url, clippedAt = new Date() }) {
  return {
    title: String(title ?? ''),
    url: String(url ?? ''),
    clipped_at: localTimestamp(clippedAt),
    note: CLIP_NOTE,
  }
}

/** JSON double-quoted strings are valid YAML double-quoted scalars. */
const yamlString = (value) => JSON.stringify(String(value ?? ''))

function frontmatter(metadata) {
  return '---\n'
    + `title: ${yamlString(metadata.title)}\n`
    + `url: ${yamlString(metadata.url)}\n`
    + `clipped_at: ${metadata.clipped_at}\n`
    + `note: ${yamlString(metadata.note)}\n`
    + '---\n'
}

/**
 * JSON is the comment payload, so a literal `--` would terminate the comment.
 * `\u002d` is a valid JSON escape and parses back to the original character.
 */
function fullPageContent(html, metadata) {
  const payload = JSON.stringify(metadata).replaceAll('--', '\\u002d\\u002d')
  const comment = `<!-- dsh-clip: ${payload} -->`
  const doctype = DOC_TYPE.exec(html)
  if (doctype === null) return `${comment}\n${html}`
  return `${doctype[0]}\n${comment}\n${html.slice(doctype[0].length)}`
}

function markdownArtifact(kind, metadata, body, clippedAt) {
  return {
    kind,
    title: metadata.title,
    url: metadata.url,
    name: clipFilename(metadata.title, 'md', clippedAt),
    type: 'text/markdown',
    content: `${frontmatter(metadata)}\n${body.trim()}\n`,
  }
}

function fullPageArtifact(metadata, html, clippedAt) {
  return {
    kind: 'full-page',
    title: metadata.title,
    url: metadata.url,
    name: clipFilename(metadata.title, 'html', clippedAt),
    type: 'text/html',
    content: fullPageContent(html, metadata),
  }
}

/**
 * @param page - capture result `{ title, url, html, text, truncated }`.
 * @param options - `{ Kernel, clippedAt }`; `Kernel` is a test seam and `clippedAt`
 *   is the capture-start time supplied by the clip pipeline.
 * @returns `{ kind, title, url, name, type, content }`
 */

export function extractArticle(page, options = {}) {
  const { Kernel = Defuddle, clippedAt } = options
  const at = clippedAt instanceof Date ? clippedAt : new Date()
  const html = String(page?.html ?? '')
  const text = String(page?.text ?? '')
  const url = String(page?.url ?? '')
  const metadata = (title) => buildMetadata({ title, url, clippedAt: at })

  let parsed
  let parsedTitle = ''
  if (html !== '') {
    try {
      parsed = new DOMParser().parseFromString(html, 'text/html')
      parsedTitle = String(parsed.title ?? '').trim()
    } catch {
      parsed = undefined
    }
  }
  const title = String(page?.title ?? '').trim() || parsedTitle || url

  if (page?.truncated === true || html === '') {
    if (text.trim() === '') throw new Error('web-clipper: page has no content')
    return markdownArtifact('text', metadata(title), text, at)
  }

  if (parsed !== undefined) {
    try {
      const result = new Kernel(parsed, { markdown: true, url }).parse()
      const markdown = String(result?.content ?? '').trim()
      const wordCount = Number(result?.wordCount ?? 0)
      if (wordCount > 0 && markdown !== '') {
        return markdownArtifact('markdown', metadata(title), markdown, at)
      }
    } catch {
      // A kernel failure degrades to the full-page snapshot instead of losing the page.
    }
  }

  if (html !== '') return fullPageArtifact(metadata(title), html, at)
  if (text.trim() !== '') return markdownArtifact('text', metadata(title), text, at)
  throw new Error('web-clipper: page has no content')
}
