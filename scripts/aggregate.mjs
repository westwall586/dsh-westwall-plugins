#!/usr/bin/env node
/**
 * 生成聚合清单（唯一真源 = 各包自己的 package.json + cordis.patch.yml）：
 *   1) 根 cordis.patch.yml —— 根行 + 每个插件包的 insert 行
 *   2) 根 package.json 的 dependencies —— 每个插件包的精确版本
 *
 * 用法：
 *   pnpm aggregate          # 重新生成
 *   pnpm aggregate:check    # 只校验（CI / 提交前）
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packagesDir = join(root, 'packages')
const SELF_NAME = '@westwall/dsh-plugins'
const SELF_ID = 'dsh-plugins'
const SELF_VERSION = '0.0.0'
/** 需要排在最前的包（例如启动期注入环境变量的包），其余按目录名字母序。 */
const MOUNT_PRIORITY = []
const CHECK = process.argv.includes('--check')

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'))

/** 从插件自己的 cordis.patch.yml 抽出 insert 行（id + 包名）。 */
function extractRows(yaml) {
  const rows = []
  const lines = yaml.split(/\r?\n/)
  for (let i = 0; i < lines.length; i++) {
    const id = /^\s*-\s+id:\s*['"]?([A-Za-z0-9._-]+)['"]?\s*$/.exec(lines[i])
    if (id === null) continue
    for (let j = i + 1; j < Math.min(lines.length, i + 5); j++) {
      if (/^\s*-\s+id:/.test(lines[j])) break
      const name = /^\s*name:\s*['"]?([^'"\s]+)['"]?\s*$/.exec(lines[j])
      if (name !== null) {
        rows.push({ id: id[1], name: name[1] })
        break
      }
    }
  }
  return rows
}

const discovered = []
for (const dir of readdirSync(packagesDir).sort()) {
  if (!/^[a-z0-9-]+$/.test(dir)) continue
  const pkgPath = join(packagesDir, dir, 'package.json')
  if (!existsSync(pkgPath)) continue
  const pkg = readJson(pkgPath)
  const patchRel = pkg.dsh?.bundle?.patch
  if (patchRel === undefined) continue
  const patchPath = join(packagesDir, dir, patchRel)
  const rows = extractRows(readFileSync(patchPath, 'utf8'))
  if (rows.length === 0) {
    console.warn(`[aggregate] 跳过 ${pkg.name}：cordis.patch.yml 里没有可提取的行`)
    continue
  }
  discovered.push({ dir, name: pkg.name, version: pkg.version, rows })
}

for (const name of MOUNT_PRIORITY) {
  if (!discovered.some((p) => p.name === name)) {
    console.error(`[aggregate] MOUNT_PRIORITY 里的 ${name} 没有匹配到任何包（写错了吗？）`)
    process.exit(1)
  }
}

const ordered = [
  ...MOUNT_PRIORITY.map((name) => discovered.find((p) => p.name === name)),
  ...discovered.filter((p) => !MOUNT_PRIORITY.includes(p.name)),
]

// 1) 根 cordis.patch.yml
const patchLines = [
  '# AUTO-GENERATED by scripts/aggregate.mjs — do not edit',
  '# 重新生成：pnpm aggregate',
  '',
  '# from self',
  '- insert:',
  `    - id: ${SELF_ID}`,
  `      name: '${SELF_NAME}'`,
]
// 一个包可以插入兄弟 bundle 的行（例如 feed-ultra 随附 web-clipper），
// 因此同一 id 可能来自多个包；根清单按首次出现保留一行，顺序仍由目录名决定。
const seenRowIds = new Set()
for (const p of ordered) {
  const rows = p.rows.filter((row) => !seenRowIds.has(row.id))
  if (rows.length === 0) continue
  for (const row of rows) seenRowIds.add(row.id)
  patchLines.push('', `# from packages/${p.dir}`, '- insert:')
  for (const row of rows) {
    patchLines.push(`    - id: ${row.id}`, `      name: '${row.name}'`)
  }
}
const expectedPatch = patchLines.join('\n') + '\n'

// 2) 根 package.json 的 dependencies（钉精确版本；保留非本仓依赖）
const rootPkgPath = join(root, 'package.json')
const rootPkg = readJson(rootPkgPath)
const deps = { ...(rootPkg.dependencies ?? {}) }
for (const key of Object.keys(deps)) {
  if (key.startsWith('@westwall/dsh-')) delete deps[key]
}
for (const p of ordered) deps[p.name] = p.version
// 没有插件时不写空的 dependencies，保证生成结果与初始骨架逐字一致。
if (Object.keys(deps).length === 0) delete rootPkg.dependencies
else rootPkg.dependencies = Object.fromEntries(Object.entries(deps).sort())
const expectedPkg = JSON.stringify(rootPkg, null, 2) + '\n'

const patchPath = join(root, 'cordis.patch.yml')
const currentPatch = existsSync(patchPath) ? readFileSync(patchPath, 'utf8') : ''
const currentPkg = readFileSync(rootPkgPath, 'utf8')

if (CHECK) {
  const problems = []
  if (currentPatch !== expectedPatch) problems.push('根 cordis.patch.yml 与包集合不一致')
  if (currentPkg !== expectedPkg) problems.push('根 package.json 的 dependencies 与包版本不一致')
  if (problems.length > 0) {
    for (const problem of problems) console.error(`[aggregate:check] ${problem}`)
    console.error('[aggregate:check] 运行 `pnpm aggregate` 后重试。')
    process.exit(1)
  }
  console.log(`[aggregate:check] OK（${ordered.length} 个插件，根版本 ${SELF_VERSION}）`)
  process.exit(0)
}

writeFileSync(patchPath, expectedPatch)
writeFileSync(rootPkgPath, expectedPkg)
console.log(`[aggregate] ${ordered.length} 个插件 → 根 cordis.patch.yml + dependencies`)
for (const p of ordered) console.log(`  - ${p.name}@${p.version}  (rows: ${p.rows.map((r) => r.id).join(', ')})`)
