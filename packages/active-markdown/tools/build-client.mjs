/** Bundle client/src/main.tsx into client.js and wrap it in the module-loader contract. */
import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const PACKAGE_ID = '@westwall/dsh-active-markdown'
const GLOBAL_NAME = 'DshActiveMarkdownClient'
const OUT = 'client.js'
const MAX_BYTES = 1.5 * 1024 * 1024

const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['client/src/main.tsx'],
  bundle: true,
  format: 'iife',
  globalName: GLOBAL_NAME,
  platform: 'browser',
  target: ['es2022'],
  jsx: 'transform',
  minify: true,
  external: ['react'],
  loader: { '.css': 'text' },
  legalComments: 'inline',
  define: { 'process.env.NODE_ENV': '"production"' },
  write: false,
  charset: 'utf8',
  logOverride: { 'empty-import-meta': 'silent' },
})

const output = `// Generated by tools/build-client.mjs; do not edit.
window.__ModuleLoader__.load({ id: '${PACKAGE_ID}', factory(require) {
${result.outputFiles[0].text}
    return ${GLOBAL_NAME}.default;
  }
});
`

const bytes = Buffer.byteLength(output)
if (bytes >= MAX_BYTES) {
  throw new Error(`tools/build-client.mjs: ${OUT} is ${bytes} bytes, over the ${MAX_BYTES}-byte guard`)
}
await writeFile(new URL(OUT, root), output)
console.log(`built ${OUT} (${bytes} bytes, ${(bytes / 1024).toFixed(0)}KB)`)
