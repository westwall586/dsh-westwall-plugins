/**
 * Bundle the browser client into client.js and wrap it in the module-loader
 * registration contract. `react` stays external because the loader's factory
 * receives the platform require.
 */
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const PACKAGE_ID = 'dsh-feed-ultra';
const GLOBAL_NAME = 'DshFeedUltraClient';
const OUT = 'client.js';

const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['client/src/main.mjs'],
  bundle: true,
  format: 'iife',
  globalName: GLOBAL_NAME,
  platform: 'browser',
  target: ['es2022'],
  loader: { '.css': 'text' },
  external: ['react'],
  legalComments: 'inline',
  write: false,
  charset: 'utf8',
  define: { 'process.env.NODE_ENV': '"production"' },
  logOverride: { 'empty-import-meta': 'silent' },
});

const output = `// Generated by tools/build.mjs; do not edit.
window.__ModuleLoader__.load({ id: '${PACKAGE_ID}', factory(require) {
${result.outputFiles[0].text}
    return ${GLOBAL_NAME}.default;
  }
});
`;
await writeFile(new URL(OUT, root), output);
console.log(`built ${OUT} (${(Buffer.byteLength(output) / 1024).toFixed(0)}KB)`);

const registration = [`id: '${PACKAGE_ID}'`, `return ${GLOBAL_NAME}.default;`];
const text = await readFile(new URL(OUT, root), 'utf8');
for (const needle of registration) {
  if (!text.includes(needle)) {
    throw new Error(`tools/build.mjs: ${OUT} lost its loader registration (${needle})`);
  }
}
