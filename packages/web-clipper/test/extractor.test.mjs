import { test } from 'node:test'
import assert from 'node:assert/strict'
import { DOMParser } from 'linkedom'

globalThis.DOMParser = DOMParser

const { CLIP_NOTE, buildMetadata, extractArticle, localTimestamp, sanitizeFilename } = await import('../client/src/extractor.mjs')

const FIXED = new Date(2026, 10, 14, 12, 30, 0)
const URL = 'https://example.com/ml-guide'
const ARTICLE = `<!doctype html><html><head><title>深度学习入门指南</title></head><body>
<nav><a href="/">首页</a></nav>
<main><article>
<h1>第一章 基础概念</h1><p>${'神经网络是由大量神经元连接构成的计算模型。'.repeat(30)}</p>
</article></main></body></html>`

/** Kernel stand-in: return one controlled defuddle result. */
function kernel(result) {
  return class {
    constructor() {}
    parse() { return result }
  }
}

function page(overrides = {}) {
  return {
    title: '深度学习入门指南',
    url: URL,
    html: ARTICLE,
    text: '',
    truncated: false,
    ...overrides,
  }
}

function metadataLines(content) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(content)
  assert.ok(match, 'content should start with frontmatter')
  return match[1].split('\n')
}

function commentMeta(content) {
  const start = content.indexOf('dsh-clip: ')
  assert.notEqual(start, -1, 'content should carry a dsh-clip comment')
  const end = content.indexOf(' -->', start)
  assert.notEqual(end, -1, 'comment should terminate')
  return { raw: content.slice(start + 'dsh-clip: '.length, end), parsed: JSON.parse(content.slice(start + 'dsh-clip: '.length, end)) }
}

test('markdown frontmatter carries exactly the four fields in order', () => {
  const artifact = extractArticle(page(), {
    Kernel: kernel({ wordCount: 637, content: '# 第一章\n\n神经网络。' }),
    clippedAt: FIXED,
  })
  assert.equal(artifact.kind, 'markdown')
  assert.deepEqual(metadataLines(artifact.content)
    .map((line) => line.slice(0, line.indexOf(':'))), ['title', 'url', 'clipped_at', 'note'])
  assert.match(artifact.content, /^---\ntitle: "深度学习入门指南"\n/)
  assert.match(artifact.content, /url: "https:\/\/example\.com\/ml-guide"\n/)
  assert.match(artifact.content, /note: "Web snapshot generated by DSH Web Clipper\. If the content is incomplete, revisit the original page\."\n/)
  assert.equal(artifact.name, '深度学习入门指南.md')
  assert.equal(artifact.type, 'text/markdown')
  assert.equal(artifact.url, URL)
})

test('clipped_at is local time with a numeric offset, not UTC', () => {
  const artifact = extractArticle(page(), {
    Kernel: kernel({ wordCount: 2, content: 'body' }),
    clippedAt: FIXED,
  })
  assert.match(artifact.content, /^clipped_at: 2026-11-14T12:30:00[+-]\d{2}:\d{2}$/m)
  assert.equal(artifact.content.includes('T12:30:00Z'), false)
  assert.equal(localTimestamp(FIXED), artifact.content.match(/^clipped_at: (.+)$/m)[1])
})

test('the note stays in metadata and never appears in the body', () => {
  const artifact = extractArticle(page(), {
    Kernel: kernel({ wordCount: 2, content: '只包含正文' }),
    clippedAt: FIXED,
  })
  const body = artifact.content.slice(artifact.content.indexOf('\n---\n') + 5)
  assert.ok(body.includes('只包含正文'))
  assert.equal(body.includes(CLIP_NOTE), false)
})

test('full-page fallback puts the four fields in one HTML comment after the doctype', () => {
  const artifact = extractArticle(page({
    title: 'Canvas App',
    url: 'https://example.com/app',
    html: '<!doctype html><html><head><title>Canvas App</title></head><body><canvas></canvas></body></html>',
  }), {
    Kernel: kernel({ wordCount: 0, content: '' }),
    clippedAt: FIXED,
  })
  assert.equal(artifact.kind, 'full-page')
  assert.equal(artifact.type, 'text/html')
  assert.equal(artifact.name, 'Canvas App.html')
  assert.ok(artifact.content.startsWith('<!doctype html>\n<!-- dsh-clip: '))
  assert.ok(artifact.content.indexOf('<canvas>') > artifact.content.indexOf('-->'))
  const { parsed } = commentMeta(artifact.content)
  assert.deepEqual(Object.keys(parsed), ['title', 'url', 'clipped_at', 'note'])
  assert.equal(parsed.title, 'Canvas App')
  assert.equal(parsed.url, 'https://example.com/app')
  assert.match(parsed.clipped_at, /^2026-11-14T12:30:00[+-]\d{2}:\d{2}$/)
  assert.equal(parsed.note, CLIP_NOTE)
})

test('the HTML comment payload escapes -- so the comment stays valid', () => {
  const artifact = extractArticle(page({
    title: 'A -- B',
    url: 'https://example.com/a--b',
    html: '<!doctype html><html><head><title>A -- B</title></head><body></body></html>',
  }), {
    Kernel: kernel({ wordCount: 0, content: '' }),
    clippedAt: FIXED,
  })
  const { raw, parsed } = commentMeta(artifact.content)
  assert.equal(raw.includes('--'), false)
  assert.equal(parsed.title, 'A - - B')
  assert.equal(parsed.url, 'https://example.com/a- -b')
})

test('text-only capture becomes a Markdown artifact', () => {
  const artifact = extractArticle({
    title: 'Plain page',
    url: 'https://example.com/text',
    html: '',
    text: '第一行\n第二行',
    truncated: true,
  }, { clippedAt: FIXED })
  assert.equal(artifact.kind, 'text')
  assert.equal(artifact.type, 'text/markdown')
  assert.equal(artifact.name, 'Plain page.md')
  assert.match(artifact.content, /^---\n/)
  assert.ok(artifact.content.includes('第一行\n第二行'))
})

test('empty page content throws so the caller can report extract-failed', () => {
  assert.throws(() => extractArticle({
    title: '', url: 'https://example.com/empty', html: '', text: '', truncated: true,
  }), /no content/)
})

test('an empty page title falls back to the final URL', () => {
  const artifact = extractArticle(page({
    title: '',
    url: 'https://example.com/fallback',
    html: '<html><head></head><body></body></html>',
  }), {
    Kernel: kernel({ wordCount: 1, content: 'body' }),
    clippedAt: FIXED,
  })
  assert.equal(artifact.title, 'https://example.com/fallback')
  assert.equal(artifact.name, 'https example.com fallback.md')
})

test('buildMetadata emits exactly four keys in order', () => {
  const metadata = buildMetadata({ title: 'T', url: 'U', clippedAt: FIXED })
  assert.deepEqual(Object.keys(metadata), ['title', 'url', 'clipped_at', 'note'])
  assert.match(metadata.clipped_at, /^2026-11-14T12:30:00[+-]\d{2}:\d{2}$/)
  assert.equal(metadata.note, CLIP_NOTE)
})

test('JSON-quoted strings keep quotes and newlines out of the YAML structure', () => {
  const artifact = extractArticle(page({ title: 'He said "hi"\nnext' }), {
    Kernel: kernel({ wordCount: 1, content: 'body' }),
    clippedAt: FIXED,
  })
  assert.ok(artifact.content.includes('title: "He said \\"hi\\"\\nnext"'))
  assert.equal(metadataLines(artifact.content).length, 4)
})

test('sanitizeFilename replaces illegal characters and falls back to untitled', () => {
  assert.equal(sanitizeFilename('', 'md'), 'untitled.md')
  const name = sanitizeFilename('a/b\\c:d*e?f"g<h>i|j', 'md')
  assert.equal(/[\\/:*?"<>|]/.test(name), false)
  assert.ok(name.endsWith('.md'))
  const long = sanitizeFilename('章'.repeat(100), 'md')
  assert.ok(long.length <= 64 + '.md'.length)
  assert.ok(long.startsWith('章'))
})