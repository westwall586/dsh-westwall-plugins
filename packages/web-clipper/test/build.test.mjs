import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const clientPath = join(root, 'client.js')

function sourceFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    return entry.isDirectory() ? sourceFiles(path) : [path]
  })
}

const client = readFileSync(clientPath, 'utf8')

test('the bundle exists, compiles, and stays under the 1.2 MB guard', () => {
  assert.ok(statSync(clientPath).size > 0)
  assert.doesNotThrow(() => { new Function(client) })
  assert.ok(Buffer.byteLength(client) < 1200 * 1024, `bundle is ${Buffer.byteLength(client)} bytes`)
})

test('the loader registration names the scoped package and returns its default export', () => {
  assert.match(client, /window\.__ModuleLoader__\.load\(\{ id: '@westwall\/dsh-web-clipper', factory\(require\) \{/)
  assert.match(client, /return DshWebClipperClient\.default;/)
  assert.match(client, /Generation by tools\/build\.mjs; do not edit|Generated by tools\/build\.mjs; do not edit/)
})

test('the self-contained bundle keeps no runtime import statement', () => {
  assert.doesNotMatch(client, /^\s*import[\s{]/m)
})

test('both official seats are registered', () => {
  assert.match(client, /sidebar\.right\.tab\.menu\.item/)
  assert.match(client, /conversation\.input\.left/)
  assert.match(client, /webClipper/)
})

test('capture anchors and the drop fallback survive bundling', () => {
  assert.match(client, /webview\[data-sidebar-browser-frame="webview"\]/)
  assert.match(client, /data-dockkit-pane-active/)
  assert.match(client, /executeJavaScript/)
  assert.match(client, /data-slot="conversation\.input\.attachments"/)
  assert.match(client, /dsh-clip:/)
})

test('no host DOM observation or toolbar/form injection ships', () => {
  assert.doesNotMatch(client, /new MutationObserver\s*\(/)
  assert.doesNotMatch(client, /\.observe\s*\(/)
  assert.doesNotMatch(client, /dwc-tool-btn/)
  assert.doesNotMatch(client, /createToolbarButton/)
})

test('the client sources contain no DOM observer or toolbar/form wiring', () => {
  for (const path of sourceFiles(join(root, 'client', 'src'))) {
    const text = readFileSync(path, 'utf8')
    assert.doesNotMatch(text, /MutationObserver/, path)
    assert.doesNotMatch(text, /toolbar/i, path)
    assert.doesNotMatch(text, /querySelector(All)?\(\s*['"][^'"]*form/, path)
  }
})

test('styles use host theme tokens and defuddle keeps its MIT notice', () => {
  assert.match(client, /--dsw-alias-/)
  assert.match(client, /defuddle/i)
  assert.match(client, /MIT License/)
})